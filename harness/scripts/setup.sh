        run: |
          set +e
          uv run pytest -q
          status=$?
          if [ "$status" = "5" ]; then
            echo "::error title=No tests collected::Add at least one test with the first code PR (pytest exit 5)."
          fi
          exit "$status"
EOF
      ;;
    pip)
      cat <<'EOF'
