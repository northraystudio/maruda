#!/usr/bin/env bash
# maruda harness installer (non-interactive).
# No language auto-detection by design: pass --langs explicitly, or --minimal
# to install only the mechanical rails and decide languages later via /maruda:setup.
set -euo pipefail

HARNESS_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TEMPLATES="$HARNESS_ROOT/templates"

usage() {
  cat <<'EOF'
Usage:
  setup.sh (--langs go,python,typescript,javascript | --minimal) [options]

Required (one of):
  --langs LIST      Comma-separated languages. First entry is the primary.
                    Supported: go, python, typescript, javascript
  --minimal         Install hooks + settings + rules only (no CLAUDE.md).
                    Fill the stack later with /maruda:setup in Claude Code.

Options:
  --target DIR      Target project directory (default: current directory)
  --name NAME       Project name for CLAUDE.md (default: target dir name)
  --branch NAME     Default branch (default: main)
  --integration-branch NAME
                    Branch that PRs target and CI gates (default: --branch).
                    Set it when releases flow through e.g. staging.
  --default-flow FLOW
                    Default flow when several Issues run at once:
                    individual | batch | stack (default: individual)
  --pm PM           Node package manager: pnpm | npm | yarn | bun (default: pnpm)
  --python-pm PM    Python package manager: uv | pip | poetry (default: uv)
  --guard-pip       Enable the "use uv, not pip install" bash guard
  --no-ci           Skip GitHub Actions CI / security-scan generation
  --no-format-hook  Skip the format-on-write hook
  --no-bash-guard   Skip the dangerous-bash guard hook
  --no-guidance-hooks  Skip the SessionStart / Stop guidance hooks
  --no-rules        Skip .claude/rules/maruda-cycle.md
  --no-env-guard    Skip .gitignore/.env.example handling
  --pr-agent        Add the advisory PR Agent workflow (qodo-ai/pr-agent; needs the OPENAI_KEY secret; never a required check)
  --protect         Apply branch protection (required status checks) via gh CLI
  --plugin          Register the maruda Claude Code plugin in .claude/settings.json
                    (extraKnownMarketplaces + enabledPlugins), so everyone who clones
                    this repository installs the same skills. Mutually exclusive with
                    --with-skills.
  --plugin-ref REF  Marketplace ref to pin (branch or tag; default: main). Marketplace
                    sources do not support a commit SHA — pin a release tag.
  --with-skills     Also run: npx skills add northraystudio/maruda --skill '*' --agent claude-code -y --copy
  --force           Overwrite existing files (default: keep existing)
  -h, --help        Show this help

With --langs, GitHub Actions workflows (ci.yml, security-scan.yml) and
.gitleaks.toml / .semgrepignore are generated by default; --minimal and
--no-ci skip them. Generated checks only gate merges once branch protection
marks them required — pass --protect (needs gh auth + admin) or configure it
in GitHub settings; the final checklist reports the current state.
--pr-agent adds .github/workflows/pr-agent.yml + .pr_agent.toml (advisory AI
review, opt-in; composes with --no-ci, not with --minimal).
--plugin only records the marketplace and marks the plugin enabled; Claude Code
does not auto-install from settings, so each user still runs /plugin install once.
The final checklist prints the exact commands.
Generated workflows also run for PRs whose base is a batch (epic/**) or an
Issue branch (feat/** fix/** refactor/**), so batched and stacked work is
verified; push triggers stay on the default and integration branches only.
EOF
}

# ── Args ─────────────────────────────────────
TARGET="$PWD"
LANGS=""
MINIMAL=0
NAME=""
BRANCH="main"
INTEGRATION_BRANCH=""
DEFAULT_FLOW="individual"
PM="pnpm"
PY_PM="uv"
GUARD_PIP=0
NO_CI=0
NO_FORMAT_HOOK=0
NO_BASH_GUARD=0
NO_GUIDANCE_HOOKS=0
NO_RULES=0
NO_ENV_GUARD=0
PROTECT=0
PR_AGENT=0
PLUGIN=0
PLUGIN_REF="main"
WITH_SKILLS=0
FORCE=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --target)     TARGET="$2"; shift 2 ;;
    --langs)      LANGS="$2"; shift 2 ;;
    --minimal)    MINIMAL=1; shift ;;
    --name)       NAME="$2"; shift 2 ;;
    --branch)     BRANCH="$2"; shift 2 ;;
    --integration-branch) INTEGRATION_BRANCH="$2"; shift 2 ;;
    --default-flow)       DEFAULT_FLOW="$2"; shift 2 ;;
    --pm)         PM="$2"; shift 2 ;;
    --python-pm)  PY_PM="$2"; shift 2 ;;
    --guard-pip)  GUARD_PIP=1; shift ;;
    --no-ci)      NO_CI=1; shift ;;
    --no-format-hook)    NO_FORMAT_HOOK=1; shift ;;
    --no-bash-guard)     NO_BASH_GUARD=1; shift ;;
    --no-guidance-hooks) NO_GUIDANCE_HOOKS=1; shift ;;
    --no-rules)          NO_RULES=1; shift ;;
    --no-env-guard)      NO_ENV_GUARD=1; shift ;;
    --protect)           PROTECT=1; shift ;;
    --pr-agent)          PR_AGENT=1; shift ;;
    --plugin)      PLUGIN=1; shift ;;
    --plugin-ref)  PLUGIN_REF="$2"; shift 2 ;;
    --with-skills) WITH_SKILLS=1; shift ;;
    --force)      FORCE=1; shift ;;
    -h|--help)    usage; exit 0 ;;
    *) echo "error: unknown option: $1" >&2; usage >&2; exit 1 ;;
  esac
done

if [[ -z "$LANGS" && "$MINIMAL" != "1" ]]; then
  echo "error: --langs is required (e.g. --langs go,typescript), or pass --minimal" >&2
  usage >&2
  exit 1
fi

if [[ "$PLUGIN" == "1" && "$WITH_SKILLS" == "1" ]]; then
  echo "error: --plugin and --with-skills are two different ways to install the same skills; pick one" >&2
  exit 1
fi

if [[ "$PR_AGENT" == "1" && "$MINIMAL" == "1" ]]; then
  echo "error: --pr-agent cannot be combined with --minimal (minimal installs nothing under .github; use --langs, optionally with --no-ci)" >&2
  exit 1
fi

case "$DEFAULT_FLOW" in
  individual|batch|stack) ;;
  *) echo "error: unsupported --default-flow: $DEFAULT_FLOW (supported: individual, batch, stack)" >&2; exit 1 ;;
esac

# The integration branch is where PRs land and where CI gates; it defaults to the
# default branch and differs only when releases flow through e.g. staging.
[[ -z "$INTEGRATION_BRANCH" ]] && INTEGRATION_BRANCH="$BRANCH"

TARGET="$(cd "$TARGET" && pwd)"
[[ -z "$NAME" ]] && NAME="$(basename "$TARGET")"

IFS=',' read -r -a LANG_ARR <<<"$LANGS"
for l in "${LANG_ARR[@]:-}"; do
  case "$l" in
    go|python|typescript|javascript|"") ;;
    *) echo "error: unsupported language: $l (supported: go, python, typescript, javascript)" >&2; exit 1 ;;
  esac
done

has_lang() {
  local l
  for l in "${LANG_ARR[@]:-}"; do [[ "$l" == "$1" ]] && return 0; done
  return 1
}

case "$PM" in pnpm|npm|yarn|bun) ;; *) echo "error: unsupported --pm: $PM" >&2; exit 1 ;; esac
case "$PY_PM" in uv|pip|poetry) ;; *) echo "error: unsupported --python-pm: $PY_PM" >&2; exit 1 ;; esac

echo "==> maruda harness → $TARGET"

# ── Status trackers for the final checklist ──
ST_HOOKS=""
ST_SETTINGS=""
ST_CLAUDE=""
ST_RULES=""
ST_CI=""
ST_ENV=""
ST_SKILLS="skipped (use --with-skills or: npx skills add northraystudio/maruda --skill '*' --agent claude-code -y --copy)"

mkdir -p "$TARGET/.claude/hooks" "$TARGET/.claude/rules"

# ── Install policy ───────────────────────────
# Existing files are never overwritten (except --force). When the incoming
# version differs from what exists, it is written alongside as "<file>.new"
# and merging is left to the user. Identical files clear any stale .new.
NEW_FILES=()
install_file() { # $1 src, $2 dst → sets INSTALL_RESULT: installed | kept | proposed
  local src="$1" dst="$2"
  if [[ ! -f "$dst" || "$FORCE" == "1" ]]; then
    cp "$src" "$dst"
    rm -f "$dst.new"
    INSTALL_RESULT=installed
  elif cmp -s "$src" "$dst"; then
    rm -f "$dst.new"
    INSTALL_RESULT=kept
  else
    cp "$src" "$dst.new"
    NEW_FILES+=("$dst.new")
    INSTALL_RESULT=proposed
  fi
}

# ── Hooks (per-component selection) ──────────
HOOK_FILES=()
DROPPED_HOOKS=""
if [[ "$NO_FORMAT_HOOK" == "1" ]]; then DROPPED_HOOKS="${DROPPED_HOOKS:+$DROPPED_HOOKS,}post-write-format.sh"; else HOOK_FILES+=(post-write-format.sh); fi
if [[ "$NO_BASH_GUARD" == "1" ]]; then DROPPED_HOOKS="${DROPPED_HOOKS:+$DROPPED_HOOKS,}pre-bash-guard.sh"; else HOOK_FILES+=(pre-bash-guard.sh); fi
if [[ "$NO_GUIDANCE_HOOKS" == "1" ]]; then
  DROPPED_HOOKS="${DROPPED_HOOKS:+$DROPPED_HOOKS,}stop-suggest-cycle.sh,session-start-context.sh"
else
  HOOK_FILES+=(stop-suggest-cycle.sh session-start-context.sh)
fi

installed=0 kept=0 proposed=0
for f in "${HOOK_FILES[@]:-}"; do
  [[ -z "$f" ]] && continue
  install_file "$TEMPLATES/hooks/$f" "$TARGET/.claude/hooks/$f"
  case "$INSTALL_RESULT" in
    installed) chmod +x "$TARGET/.claude/hooks/$f"; installed=$((installed + 1)) ;;
    kept)      kept=$((kept + 1)) ;;
    proposed)  chmod +x "$TARGET/.claude/hooks/$f.new"; proposed=$((proposed + 1)) ;;
  esac
done
ST_HOOKS="installed=$installed kept=$kept proposed=$proposed${DROPPED_HOOKS:+ (skipped: $DROPPED_HOOKS)}"

# ── settings.json (create or merge hooks) ────
# The settings template must only register the hooks actually installed.
SETTINGS="$TARGET/.claude/settings.json"
SETTINGS_SRC="$TEMPLATES/settings.json.template"
if [[ -n "$DROPPED_HOOKS" ]]; then
  if command -v jq >/dev/null 2>&1; then
    SETTINGS_SRC="$(mktemp)"
    jq --arg drop "$DROPPED_HOOKS" '
      ($drop | split(",") | map(select(length > 0))) as $d
      | .hooks |= (with_entries(
          .value |= map(select(
            ((.hooks[0].command) // "") as $c
            | (($d | any(. as $n | $c | contains($n))) | not)
          ))
        ) | with_entries(select((.value | length) > 0)))
    ' "$TEMPLATES/settings.json.template" >"$SETTINGS_SRC"
  else
    echo "warn: jq unavailable — settings.json will still reference skipped hooks; remove those entries manually" >&2
  fi
fi
if [[ ! -f "$SETTINGS" || "$FORCE" == "1" ]]; then
  cp "$SETTINGS_SRC" "$SETTINGS"
  ST_SETTINGS="created"
elif command -v jq >/dev/null 2>&1; then
  tmp="$(mktemp)"
  jq -s '
    (.[0].hooks // {}) as $cur | (.[1].hooks // {}) as $tpl |
    .[0] + {hooks: (
      ($cur | to_entries) + ($tpl | to_entries)
      | group_by(.key)
      | map({key: .[0].key, value: (map(.value) | add | unique_by(tostring))})
      | from_entries
    )}
  ' "$SETTINGS" "$SETTINGS_SRC" >"$tmp"
  mv "$tmp" "$SETTINGS"
  ST_SETTINGS="merged (existing hooks preserved)"
else
  cp "$SETTINGS_SRC" "$SETTINGS.new"
  NEW_FILES+=("$SETTINGS.new")
  ST_SETTINGS="kept existing (jq unavailable) — proposed hooks config at settings.json.new"
fi

# Enable the pip guard via settings env when requested
if [[ "$GUARD_PIP" == "1" ]]; then
  if command -v jq >/dev/null 2>&1; then
    tmp="$(mktemp)"
    jq '.env = ((.env // {}) + {DEV_SKILLS_GUARD_PIP: "1"})' "$SETTINGS" >"$tmp"
    mv "$tmp" "$SETTINGS"
    ST_SETTINGS="$ST_SETTINGS + pip guard enabled"
  else
    echo "warn: --guard-pip needs jq to edit settings.json; add {\"env\":{\"DEV_SKILLS_GUARD_PIP\":\"1\"}} manually" >&2
  fi
fi

# ── Plugin registration (marketplace + enabled plugin) ──
# Claude Code does not auto-install from settings: these two keys make the
# marketplace known and mark the plugin enabled, and each user still runs
# /plugin install once. Existing entries are merged, never replaced.
ST_PLUGIN="skipped (use --plugin to pin the maruda plugin for everyone who clones this repository)"
if [[ "$PLUGIN" == "1" ]]; then
  if command -v jq >/dev/null 2>&1; then
    tmp="$(mktemp)"
    jq --arg ref "$PLUGIN_REF" '
      .extraKnownMarketplaces = ((.extraKnownMarketplaces // {}) + {
        northraystudio: {source: {source: "github", repo: "northraystudio/maruda", ref: $ref}}
      })
      | .enabledPlugins = ((.enabledPlugins // {}) + {"maruda@northraystudio": true})
    ' "$SETTINGS" >"$tmp"
    mv "$tmp" "$SETTINGS"
    ST_PLUGIN="registered (northraystudio @ $PLUGIN_REF) — each user runs: /plugin install maruda@northraystudio"
  else
    ST_PLUGIN="FAILED — needs jq; add extraKnownMarketplaces + enabledPlugins to .claude/settings.json manually"
    echo "warn: --plugin needs jq to edit settings.json" >&2
  fi
fi

# ── Rules (cycle + score-aligned coding rules) ──
if [[ "$NO_RULES" == "1" ]]; then
  ST_RULES="skipped (--no-rules)"
else
  RULE_FILES=(maruda-cycle.md coding-principles.md)
  has_lang go && RULE_FILES+=(go.md)
  has_lang python && RULE_FILES+=(python.md)
  if has_lang typescript || has_lang javascript; then RULE_FILES+=(typescript.md); fi
  rules_installed=0 rules_kept=0 rules_proposed=0
  for f in "${RULE_FILES[@]}"; do
    install_file "$TEMPLATES/rules/$f" "$TARGET/.claude/rules/$f"
    case "$INSTALL_RESULT" in
      installed) rules_installed=$((rules_installed + 1)) ;;
      kept)      rules_kept=$((rules_kept + 1)) ;;
      proposed)  rules_proposed=$((rules_proposed + 1)) ;;
    esac
  done
  ST_RULES="installed=$rules_installed kept=$rules_kept proposed=$rules_proposed (${RULE_FILES[*]})"
  # The cycle rule was called dev-skills-cycle.md before the maruda rename. The
  # installer never deletes what it did not write, so say it out loud instead.
  if [[ -f "$TARGET/.claude/rules/dev-skills-cycle.md" ]]; then
    ST_RULES="$ST_RULES — legacy dev-skills-cycle.md still present; delete it (replaced by maruda-cycle.md)"
  fi
fi

# ── CLAUDE.md ────────────────────────────────
node_block() { # $1: TypeScript|JavaScript
  local lang="$1" run exec_cmd
  case "$PM" in
    pnpm) run="pnpm" exec_cmd="pnpm exec" ;;
    npm)  run="npm"  exec_cmd="npx" ;;
    yarn) run="yarn" exec_cmd="yarn" ;;
    bun)  run="bun"  exec_cmd="bunx" ;;
  esac
  printf '### %s (%s)\n' "$lang" "$PM"
  printf -- '- Install: `%s install`\n' "$run"
  printf -- '- Test: `%s test`\n' "$run"
  printf -- '- Lint: `%s run lint`\n' "$run"
  [[ "$lang" == "TypeScript" ]] && printf -- '- Typecheck: `%s tsc --noEmit`\n' "$exec_cmd"
  printf -- '- Format: Prettier (hook on Write/Edit)\n'
}

python_block() {
  printf '### Python (%s)\n' "$PY_PM"
  case "$PY_PM" in
    uv)
      printf -- '- Install: `uv sync`\n- Test: `uv run pytest`\n- Lint / Format: `uv run ruff check` / `uv run ruff format` (format hook on Write/Edit)\n' ;;
    pip)
      printf -- '- Install: `pip install -e .`\n- Test: `pytest`\n- Lint / Format: `ruff check` / `ruff format` (format hook on Write/Edit)\n' ;;
    poetry)
      printf -- '- Install: `poetry install`\n- Test: `poetry run pytest`\n- Lint / Format: `poetry run ruff check` / `poetry run ruff format` (format hook on Write/Edit)\n' ;;
  esac
}

go_block() {
  printf '### Go\n- Install: `go mod download`\n- Test: `go test ./...`\n- Lint: `golangci-lint run` (fallback: `go vet ./...`)\n- Format: goimports / gofmt (hook on Write/Edit)\n'
}

lang_title() {
  case "$1" in
    go) echo "Go" ;;
    python) echo "Python" ;;
    typescript) echo "TypeScript" ;;
    javascript) echo "JavaScript" ;;
  esac
}

CLAUDE_MD="$TARGET/CLAUDE.md"
if [[ "$MINIMAL" == "1" ]]; then
  ST_CLAUDE="skipped (--minimal) — run /maruda:setup in Claude Code to fill the stack"
else
  primary="$(lang_title "${LANG_ARR[0]}")"
  others=""
  if [[ ${#LANG_ARR[@]} -gt 1 ]]; then
    for l in "${LANG_ARR[@]:1}"; do
      t="$(lang_title "$l")"
      others="${others:+$others, }$t"
    done
  fi
  STACK_BLOCKS="Primary: $primary"
  [[ -n "$others" ]] && STACK_BLOCKS+=$'\n'"Also present: $others"
  STACK_BLOCKS+=$'\n'
  for l in "${LANG_ARR[@]}"; do
    STACK_BLOCKS+=$'\n'
    case "$l" in
      go)         STACK_BLOCKS+="$(go_block)" ;;
      python)     STACK_BLOCKS+="$(python_block)" ;;
      typescript) STACK_BLOCKS+="$(node_block TypeScript)" ;;
      javascript) STACK_BLOCKS+="$(node_block JavaScript)" ;;
    esac
    STACK_BLOCKS+=$'\n'
  done

  tmp_claude="$(mktemp)"
  {
    while IFS= read -r line; do
      if [[ "$line" == "{{STACK_BLOCKS}}" ]]; then
        printf '%s\n' "$STACK_BLOCKS"
      else
        line=${line//\{\{PROJECT_NAME\}\}/$NAME}
        line=${line//\{\{DEFAULT_BRANCH\}\}/$BRANCH}
        line=${line//\{\{INTEGRATION_BRANCH\}\}/$INTEGRATION_BRANCH}
        line=${line//\{\{DEFAULT_FLOW\}\}/$DEFAULT_FLOW}
        printf '%s\n' "$line"
      fi
    done <"$TEMPLATES/CLAUDE.md.template"
  } >"$tmp_claude"
  install_file "$tmp_claude" "$CLAUDE_MD"
  rm -f "$tmp_claude"
  case "$INSTALL_RESULT" in
    installed) ST_CLAUDE="created ($primary${others:+ + $others})" ;;
    kept)      ST_CLAUDE="up to date" ;;
    proposed)  ST_CLAUDE="kept existing — proposed version at CLAUDE.md.new (merge manually or via /maruda:setup)" ;;
  esac
fi

# ── GitHub Actions CI + security scan ────────
go_ci_job() {
  cat <<'EOF'
  go:
    name: Go (build, test, lint)
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4.4.0
      - name: Check go.mod exists
        # Before setup-go, which itself reads go.mod (go-version-file).
        run: |
          if [ ! -f go.mod ]; then
            echo "::error title=Missing go.mod::Run 'go mod init <module>' and commit go.mod before the first Go PR."
            exit 1
          fi
      - uses: actions/setup-go@40f1582b2485089dde7abd97c1529aa768e1baff # v5.6.0
        id: go
        with:
          go-version-file: go.mod
      - name: go mod tidy check
        run: |
          go mod tidy
          git diff --exit-code go.mod
          if [ -f go.sum ]; then git diff --exit-code go.sum; fi
      - name: Build
        run: go build ./...
      - name: Test (race)
        run: go test ./... -race
      - name: Cache golangci-lint
        # Dedicated versioned tool dir; cold installs keep Go module checksum
        # verification, warm runs skip the compile.
        uses: actions/cache@0057852bfaa89a56745cba8c7296529d2fc39830 # v4.3.0
        with:
          path: ~/.golangci-lint-bin/v2.12.2
          key: golangci-lint-${{ runner.os }}-${{ runner.arch }}-go${{ steps.go.outputs.go-version }}-v2.12.2
      - name: Lint
        # Supply chain: exact pinned version (never @latest).
        run: |
          BIN="$HOME/.golangci-lint-bin/v2.12.2"
          if [ ! -x "$BIN/golangci-lint" ]; then
            GOBIN="$BIN" go install github.com/golangci/golangci-lint/v2/cmd/golangci-lint@v2.12.2
          fi
          "$BIN/golangci-lint" version
          "$BIN/golangci-lint" run --timeout=5m
EOF
}

node_ci_job() {
  local req="'lint', 'test'" run_prefix ts=0
  if has_lang typescript; then ts=1; req="'lint', 'typecheck', 'test'"; fi
  case "$PM" in
    pnpm) run_prefix="pnpm run" ;;
    npm)  run_prefix="npm run" ;;
    yarn) run_prefix="yarn" ;;
    bun)  run_prefix="bun run" ;;
  esac

  cat <<'EOF'
  node:
    name: Node (lint, typecheck, test)
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4.4.0
      # Preflight before install: strict by design (shift-left), but fail with
      # an actionable message instead of a raw "missing script" error. The
      # manifest is parsed directly — package-manager stderr is version-fragile.
      - name: Validate required package scripts
        run: |
          node <<'NODE'
          const fs = require('fs');
          if (!fs.existsSync('package.json')) {
            console.error('::error file=package.json,title=Missing package.json::Create package.json with the required scripts before the first code PR.');
            process.exit(1);
          }
          let pkg;
          try { pkg = JSON.parse(fs.readFileSync('package.json', 'utf8')); }
          catch (e) {
            console.error('::error file=package.json,title=Invalid package.json::package.json is not valid JSON.');
            process.exit(1);
          }
EOF
  printf '          const required = [%s];\n' "$req"
  cat <<'EOF'
          let failed = false;
          for (const name of required) {
            const v = (pkg.scripts || {})[name];
            if (typeof v !== 'string' || v.trim() === '') {
              console.error('::error file=package.json,title=Missing npm script::Add scripts.' + name + ' to package.json before the first code PR.');
              failed = true;
            }
          }
          if (failed) process.exit(1);
          NODE
EOF
  case "$PM" in
    pnpm)
      cat <<'EOF'
      - uses: pnpm/action-setup@fc06bc1257f339d1d5d8b3a19a8cae5388b55320 # v4.4.0
        with:
          version: 10
      - uses: actions/setup-node@49933ea5288caeca8642d1e84afbd3f7d6820020 # v4.4.0
        with:
          node-version: '22'
          cache: pnpm
      - name: Install dependencies
        run: pnpm install --frozen-lockfile
EOF
      ;;
    npm)
      cat <<'EOF'
      - uses: actions/setup-node@49933ea5288caeca8642d1e84afbd3f7d6820020 # v4.4.0
        with:
          node-version: '22'
          cache: npm
      - name: Install dependencies
        run: npm ci
EOF
      ;;
    yarn)
      cat <<'EOF'
      - uses: actions/setup-node@49933ea5288caeca8642d1e84afbd3f7d6820020 # v4.4.0
        with:
          node-version: '22'
          cache: yarn
      - name: Install dependencies
        run: yarn install --frozen-lockfile
EOF
      ;;
    bun)
      cat <<'EOF'
      - uses: oven-sh/setup-bun@0c5077e51419868618aeaa5fe8019c62421857d6 # v2.2.0
      - name: Install dependencies
        run: bun install --frozen-lockfile
EOF
      ;;
  esac
  printf '      - name: Lint\n        run: %s lint\n' "$run_prefix"
  if [[ "$ts" == "1" ]]; then
    printf '      - name: Typecheck\n        run: %s typecheck\n' "$run_prefix"
  fi
  printf '      - name: Test\n        run: %s test\n' "$run_prefix"
}

python_ci_job() {
  echo "  python:"
  echo "    name: Python (lint, test)"
  echo "    runs-on: ubuntu-latest"
  echo "    steps:"
  echo "      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4.4.0"
  case "$PY_PM" in
    uv)
      cat <<'EOF'
      - uses: astral-sh/setup-uv@d4b2f3b6ecc6e67c4457f6d3e41ec42d3d0fcb86 # v5.4.2
      - name: Install dependencies
        run: uv sync
      - name: Lint (ruff)
        run: |
          uv run ruff check .
          uv run ruff format --check .
      - name: Test
        # Strict by design (shift-left): "no tests collected" (exit 5) fails
